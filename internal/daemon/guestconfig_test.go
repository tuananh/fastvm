func TestParseHostResolvFiltersLoopbackAndKeepsSearchOptions(t *testing.T) {
	data := `# Generated by Docker
nameserver 127.0.0.53
nameserver 100.100.100.100
nameserver 8.8.8.8
search tailnet-057a.ts.net corp.example
options ndots:5 rotate
`
	ns, search, options := parseHostResolv(data)
	if len(ns) != 2 || ns[0] != "100.100.100.100" || ns[1] != "8.8.8.8" {
		t.Fatalf("nameservers = %v", ns)
	}
	if len(search) != 2 || search[0] != "tailnet-057a.ts.net" {
		t.Fatalf("search = %v", search)
	}
	if len(options) != 1 || options[0] != "ndots:5 rotate" {
		t.Fatalf("options = %v", options)
	}
}

func TestRenderResolvConfFallsBackWhenOnlyLoopback(t *testing.T) {
	ns, search, options := parseHostResolv("nameserver 127.0.0.1\n")
	body := renderResolvConf(ns, search, options)
	if !strings.Contains(body, "nameserver 8.8.8.8") ||
		!strings.Contains(body, "nameserver 8.8.4.4") {
		t.Fatalf("expected public fallback, got:\n%s", body)
	}
}

func TestGuestHostnameIsDockerLike(t *testing.T) {
	if got := guestHostname("0123456789abcdef0123"); got != "0123456789ab" {
		t.Fatalf("hostname = %q", got)
	}
	if got := guestHostname(""); got != "fastvm" {
		t.Fatalf("empty hostname = %q", got)
	}
}

func TestRenderHostsIncludesGuestAddress(t *testing.T) {
	body := renderHosts("10.77.0.2", "0123456789ab")
	for _, want := range []string{
		"127.0.0.1\tlocalhost",
		"::1\tlocalhost ip6-localhost ip6-loopback",
		"10.77.0.2\t0123456789ab",
	} {
		if !strings.Contains(body, want) {
			t.Errorf("hosts missing %q:\n%s", want, body)
		}
	}
}

func TestBootCmdlineCarriesGuestIdentity(t *testing.T) {
	sb := types.Sandbox{TAPName: "tap0", IP: "10.77.0.2", Gateway: "10.77.0.1"}
	guest := guestBootFiles{
		Hostname: "0123456789ab",
		Resolv:   "nameserver 8.8.8.8\n",
		Hosts:    "127.0.0.1 localhost\n",
	}
	cmd := bootCmdline(&sb, "deadbeef", guest)
	for _, want := range []string{
		"fastvm.hostname=0123456789ab",
		"fastvm.resolv=",
		"fastvm.hosts=",
		"fastvm.seed=deadbeef",
	} {
		if !strings.Contains(cmd, want) {
			t.Errorf("cmdline missing %q: %s", want, cmd)
		}
	}
}

func TestGuestBootFilesNetworkOverrides(t *testing.T) {
	d := &Daemon{cfg: &config.Config{Network: config.Network{
		DNS:    []string{"9.9.9.9"},
		Search: []string{"corp.example"},
	}}}
	sb := types.Sandbox{ID: "0123456789abcdef", IP: "10.77.0.2"}
	files := d.guestBootFiles(&sb)
	if !strings.Contains(files.Resolv, "nameserver 9.9.9.9") {
		t.Errorf("override DNS missing:\n%s", files.Resolv)
	}
	if strings.Contains(files.Resolv, "8.8.8.8") {
		t.Errorf("host/fallback DNS leaked into override:\n%s", files.Resolv)
	}
	if !strings.Contains(files.Resolv, "search corp.example") {
		t.Errorf("override search missing:\n%s", files.Resolv)
	}
	if files.Hostname != "0123456789ab" {
		t.Errorf("hostname = %q", files.Hostname)
	}
}
