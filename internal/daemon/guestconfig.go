package daemon

import (
	"encoding/base64"
	"fmt"
	"net"
	"os"
	"strings"

	"fastvm/internal/types"
)

// guestBootFiles are per-boot files the daemon generates and passes to the
// guest agent. Docker bind-mounts generated /etc/resolv.conf, /etc/hosts and
// /etc/hostname into containers; fastvm has no such bind-mount path, so the
// agent writes them into the sandbox's writable root disk before starting the
// workload.
type guestBootFiles struct {
	Hostname string
	Resolv   string
	Hosts    string
}

const (
	// cmdlineGuestResolvKey etc. are base64-encoded to keep multi-line files
	// safe inside the kernel command line.
	cmdlineGuestResolvKey   = "fastvm.resolv"
	cmdlineGuestHostsKey    = "fastvm.hosts"
	cmdlineGuestHostnameKey = "fastvm.hostname"

	guestHostnameLen = 12
)

// readHostResolv is a test seam; the daemon mirrors the host resolver by default.
var readHostResolv = func() ([]byte, error) { return os.ReadFile("/etc/resolv.conf") }

func (d *Daemon) guestBootFiles(sb *types.Sandbox) guestBootFiles {
	hostname := guestHostname(sb.ID)
	nameservers, search, options := hostResolvHints(d)
	if len(d.cfg.Network.DNS) > 0 {
		nameservers = append([]string(nil), d.cfg.Network.DNS...)
	}
	if len(d.cfg.Network.Search) > 0 {
		search = append([]string(nil), d.cfg.Network.Search...)
	}
	return guestBootFiles{
		Hostname: hostname,
		Resolv:   renderResolvConf(nameservers, search, options),
		Hosts:    renderHosts(sb.IP, hostname),
	}
}

func guestHostname(id string) string {
	id = strings.TrimSpace(id)
	if id == "" {
		return "fastvm"
	}
	// Docker's default container hostname is the first 12 hex chars of the
	// container ID; mirror that for sandbox IDs.
	if len(id) > guestHostnameLen {
		id = id[:guestHostnameLen]
	}
	var b strings.Builder
	for _, r := range strings.ToLower(id) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' {
			b.WriteRune(r)
		}
	}
	if b.Len() == 0 {
		return "fastvm"
	}
	return b.String()
}

// hostResolvHints extracts usable nameservers/search/options from the host's
// resolver. Like Docker, loopback and unspecified nameservers are dropped
// because the guest cannot reach the host's loopback.
func hostResolvHints(d *Daemon) (nameservers, search, options []string) {
	data, err := readHostResolv()
	if err != nil {
		if d != nil && d.log != nil {
			d.log.Warn("read host resolver; using fallback DNS", "err", err)
		}
		return nil, nil, nil
	}
	return parseHostResolv(string(data))
}

func parseHostResolv(data string) (nameservers, search, options []string) {
	seenNS := make(map[string]bool)
	seenSearch := make(map[string]bool)
	for _, line := range strings.Split(data, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, ";") {
			continue
		}
		if i := strings.IndexAny(line, "#;"); i >= 0 {
			line = strings.TrimSpace(line[:i])
		}
		fields := strings.Fields(line)
		if len(fields) < 2 {
			continue
		}
		switch strings.ToLower(fields[0]) {
		case "nameserver":
			ip := net.ParseIP(fields[1])
			if ip == nil || ip.To4() == nil || ip.IsLoopback() || ip.IsUnspecified() {
				continue
			}
			if seenNS[ip.String()] || len(nameservers) >= 3 {
				continue
			}
			seenNS[ip.String()] = true
			nameservers = append(nameservers, ip.String())
		case "search":
			for _, domain := range fields[1:] {
				if seenSearch[domain] || len(search) >= 6 {
					continue
				}
				seenSearch[domain] = true
				search = append(search, domain)
			}
		case "options":
			options = append(options, strings.Join(fields[1:], " "))
		}
	}
	return nameservers, search, options
}

func renderResolvConf(nameservers, search, options []string) string {
	if len(nameservers) == 0 {
		// Docker falls back to public resolvers when the host only offers
		// loopback DNS.
		nameservers = []string{"8.8.8.8", "8.8.4.4"}
	}
	var b strings.Builder
	b.WriteString("# Generated by fastvm from the host resolver\n")
	for _, ns := range nameservers {
		fmt.Fprintf(&b, "nameserver %s\n", ns)
	}
	if len(search) > 0 {
		fmt.Fprintf(&b, "search %s\n", strings.Join(search, " "))
	}
	for _, opt := range options {
		fmt.Fprintf(&b, "options %s\n", opt)
	}
	return b.String()
}

func renderHosts(ip, hostname string) string {
	var b strings.Builder
	b.WriteString("# Generated by fastvm\n")
	b.WriteString("127.0.0.1\tlocalhost\n")
	b.WriteString("::1\tlocalhost ip6-localhost ip6-loopback\n")
	if parsed := net.ParseIP(ip); parsed != nil && parsed.To4() != nil {
		fmt.Fprintf(&b, "%s\t%s\n", parsed.String(), hostname)
	}
	return b.String()
}

func encodeCmdlineFile(s string) string {
	if s == "" {
		return ""
	}
	return base64.StdEncoding.EncodeToString([]byte(s))
}
